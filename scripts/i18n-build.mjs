import { mkdir, readdir, readFile, writeFile, rm } from 'node:fs/promises';
import path from 'node:path';

// Generated before `expo start` and `expo export` (npm run start / web / build), never committed:
//
// 1. public/locales/<code>.js from src/i18n/locales/<code>.json: a script that registers a
//    language's strings before the app hydrates.
// 2. src/app/(i18n)/<code>/…: the /<code>/ copy of every page that has a localized URL. Each file
//    re-exports the English route and tells its metadata which language it is. (A single dynamic
//    [lang] folder would be simpler, but Expo's exporter does not fill a parent segment into
//    loader data keys, so every language would share one broken key.)
//
// The language list comes from the src/i18n/locales/*.json files present, so adding a language
// is its locale file plus its entry in src/i18n/locales.ts.

const root = process.cwd();
const source = path.join(root, 'src/i18n/locales');
const scripts = path.join(root, 'public/locales');
const app = path.join(root, 'src/app');
const generated = path.join(app, '(i18n)');

const config = await readFile(path.join(root, 'src/i18n/locales.ts'), 'utf8');
const configured = new Set([...config.matchAll(/\{ code: '([a-z]{2,3})'/g)].map((m) => m[1]));
const codes = (await readdir(source))
  .filter((file) => file.endsWith('.json'))
  .map((file) => file.slice(0, -5))
  .filter((code) => code !== 'en');
for (const code of codes)
  if (!configured.has(code)) throw new Error(`${code}.json has no entry in src/i18n/locales.ts`);
for (const code of configured)
  if (code !== 'en' && !codes.includes(code))
    throw new Error(
      `src/i18n/locales.ts lists ${code}, but src/i18n/locales/${code}.json is missing`,
    );

await rm(scripts, { recursive: true, force: true });
await mkdir(scripts, { recursive: true });
for (const code of codes) {
  const strings = JSON.parse(await readFile(path.join(source, `${code}.json`), 'utf8'));
  const json = JSON.stringify(strings).replace(/</g, '\\u003c');
  await writeFile(
    path.join(scripts, `${code}.js`),
    `(self.__MH_I18N__=self.__MH_I18N__||{})[${JSON.stringify(code)}]=${json};\n`,
  );
}

// Pages without a localized URL: one per mantra, deity, book and section, plus the blog shell.
// Keep in step with hasLocalizedUrl() in src/i18n/locales.ts.
const catalog =
  /^(library\/mantras\/(\[slug\]|deity\/)|library\/books\/\[book\]|blog-shell|\+|_layout|\(i18n\))/;
const routes = [];
for (const entry of await readdir(app, { recursive: true, withFileTypes: true })) {
  if (!entry.isFile() || !entry.name.endsWith('.tsx')) continue;
  const file = path
    .relative(app, path.join(entry.parentPath, entry.name))
    .split(path.sep)
    .join('/');
  if (!catalog.test(file)) routes.push(file);
}

await rm(generated, { recursive: true, force: true });
for (const code of codes)
  for (const file of routes) {
    const out = path.join(generated, code, file);
    await mkdir(path.dirname(out), { recursive: true });
    const english = await readFile(path.join(app, file), 'utf8');
    const target = path
      .relative(path.dirname(out), path.join(app, file.slice(0, -4)))
      .split(path.sep)
      .join('/');
    const lines = [
      `// Generated by scripts/i18n-build.mjs: /${code}/${file.slice(0, -4).replace(/(^|\/)index$/, '')} in ${code}.`,
      `import * as page from '${target}';`,
      `export { default } from '${target}';`,
    ];
    if (/export (const|function|async function) loader\b/.test(english))
      lines.push(
        '',
        '// Declared here so the exporter sees that this route has a loader.',
        'export const loader = page.loader;',
      );
    if (/generateStaticParams/.test(english))
      lines.push('export const generateStaticParams = page.generateStaticParams;');
    if (/generateMetadata/.test(english))
      lines.push(
        '',
        'export function generateMetadata(request: unknown, params?: Record<string, string | string[]>) {',
        `  return page.generateMetadata(request, { ...params, lang: '${code}' });`,
        '}',
      );
    await writeFile(out, lines.join('\n') + '\n');
  }
console.log(`i18n: ${codes.length} languages, ${routes.length} localized routes each`);
